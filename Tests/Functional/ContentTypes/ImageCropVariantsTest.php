declare(strict_types=1);

namespace FriendsOfTYPO3\Headless\Tests\Functional\ContentTypes;

use TYPO3\TestingFramework\Core\Functional\Framework\Frontend\InternalRequest;

class ImageCropVariantsTest extends BaseContentTypeTesting
{
    protected array $typoScriptSetupFiles = [
        'EXT:headless/Configuration/TypoScript/setup.typoscript',
        'EXT:headless/Tests/Functional/Fixtures/CropVariants.typoscript',
    ];

    public function setUp(): void
    {
        parent::setUp();

        $this->importCSVDataSet(__DIR__ . '/../Fixtures/crop_variants.csv');
    }

    public function testSingleNamedCropVariantAndOriginalAreExposedWithAutogeneratedUrls(): void
    {
        $response = $this->executeFrontendSubRequest(
            new InternalRequest('https://website.local/')
        );

        self::assertSame(200, $response->getStatusCode());

        $fullTree = json_decode((string)$response->getBody(), true);

        $contentElement = $fullTree['content']['colPos3'][0];
        self::assertEquals(40, $contentElement['id'], 'id mismatch');

        $file = $contentElement['content']['gallery']['rows'][1]['columns'][1];

        self::assertEquals(18, $file['properties']['cropDimensions']['width'], 'top level must stay uncropped without a default variant');
        self::assertEquals(16, $file['properties']['cropDimensions']['height'], 'top level must stay uncropped without a default variant');
        self::assertArrayHasKey('urlRetina', $file, 'top level autogenerate url missing');

        self::assertIsArray($file['cropVariants'] ?? null, 'cropVariants missing for a single named variant');
        self::assertSame(['desktop'], array_keys($file['cropVariants']), 'cropVariants keys mismatch');

        $desktop = $file['cropVariants']['desktop'];

        self::assertNotEmpty($desktop['publicUrl'], 'desktop publicUrl missing');
        self::assertNotEmpty($desktop['urlRetina'] ?? null, 'desktop autogenerate url missing');
        self::assertIsArray($desktop['properties']['dimensions'] ?? null, 'desktop dimensions missing');

        $original = $file['original'] ?? null;

        self::assertIsArray($original, 'original missing with includeOriginal = 1');
        self::assertNotEmpty($original['publicUrl'], 'original publicUrl missing');
        self::assertNotEmpty($original['urlRetina'] ?? null, 'original autogenerate url missing');
        self::assertEquals(18, $original['properties']['dimensions']['width'], 'original width mismatch');
        self::assertEquals(16, $original['properties']['dimensions']['height'], 'original height mismatch');
    }
}
